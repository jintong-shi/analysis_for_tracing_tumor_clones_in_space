#!/usr/bin/env bash
set -euo pipefail

# Run every best-case config under config/<dataset>/.
# Top-level config/*.yaml are ignored on purpose (base config / template).
#
# Two phases, because the two inferCNV variants share one output folder:
#   1. all non-HMM configs
#   2. the *__infercnv_hmm.yaml configs — each preceded by renaming the
#      existing <combo>/infercnv to <combo>/infercnv_regular, so the HMM run
#      writes a fresh infercnv/ and 01_standardize_cnv_output_realdata.R can
#      read infercnv_expr from _regular and infercnv_cnv from infercnv/.
# Running phase 2 first, or interleaved, would overwrite the non-HMM output.
#
# A failing config is reported and skipped, not fatal; the exit code is 1 if any
# config failed.
#
# Override cores:  SMK_CORES=16 bash run_all.sh
# Limit to one dataset:  DATASETS=skin_tumor_ff bash run_all.sh

# export MAMBA_ROOT_PREFIX=<TOOLS_ROOT>/.mamba
# eval "$(micromamba shell hook -s bash)"

export BASE=<TOOLS_ROOT>/snakemake
export XDG_CACHE_HOME="$BASE/cache"
export TMPDIR="$BASE/tmp"
export PIP_CACHE_DIR="$BASE/pip"
export MPLCONFIGDIR="$BASE/mpl"
export R_USER_CACHE_DIR="$BASE/rcache"
export OMP_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 MKL_NUM_THREADS=1 VECLIB_MAXIMUM_THREADS=1

PIPE_DIR=$(cd "$(dirname "$0")" && pwd)
CONFIG_DIR="$PIPE_DIR/config"
CORES=${SMK_CORES:-8}
DATASETS=${DATASETS:-}

cd "$PIPE_DIR"

# Collect configs, non-HMM first. mindepth/maxdepth 2 == only the per-dataset
# subfolders, so the base config and template at the top level are skipped.
mapfile -t REGULAR_CFGS < <(find "$CONFIG_DIR" -mindepth 2 -maxdepth 2 -name '*.yaml' \
  ! -name '*__infercnv_hmm.yaml' | sort)
mapfile -t HMM_CFGS < <(find "$CONFIG_DIR" -mindepth 2 -maxdepth 2 -name '*__infercnv_hmm.yaml' | sort)

if [[ -n "$DATASETS" ]]; then
  mapfile -t REGULAR_CFGS < <(printf '%s\n' "${REGULAR_CFGS[@]}" | grep "/$DATASETS/" || true)
  mapfile -t HMM_CFGS < <(printf '%s\n' "${HMM_CFGS[@]}" | grep "/$DATASETS/" || true)
fi

if (( ${#REGULAR_CFGS[@]} + ${#HMM_CFGS[@]} == 0 )); then
  echo "[FATAL] no configs found under $CONFIG_DIR" >&2
  exit 2
fi
echo "[PLAN] ${#REGULAR_CFGS[@]} non-HMM + ${#HMM_CFGS[@]} inferCNV-HMM configs, cores=$CORES"

# Echo "<outroot>/<sample>/<combo display name>" for a config. These configs are
# machine-generated by scripts/generate_bestcase_configs.py with a fixed shape:
# `sample:` and `outroot:` are flat quoted scalars and `display:` holds exactly
# one entry, so awk is enough and this stays free of a PyYAML dependency.
combo_dir_of() {
  awk -F'"' '
    /^sample:/  { sample = $2 }
    /^outroot:/ { outroot = $2 }
    /^display:/ { getline; split($0, a, "\""); display = a[2] }
    END {
      if (sample == "" || outroot == "" || display == "") exit 1
      print outroot "/" sample "/" display
    }' "$1"
}

ok=0
fail=0
failed_cfgs=()

run_one() {
  local cfg="$1"
  echo "[START] $(date '+%F %T') ${cfg#$PIPE_DIR/}"

  # Unlock first (nothing to unlock is fine).
  snakemake --use-conda --unlock --configfile "$cfg" --cores 1 || true

  if snakemake --use-conda --configfile "$cfg" \
      --cores "$CORES" --rerun-incomplete --rerun-triggers mtime -p; then
    ok=$((ok + 1))
    echo "[DONE]  $(date '+%F %T') ${cfg#$PIPE_DIR/}"
  else
    fail=$((fail + 1))
    failed_cfgs+=("$cfg")
    echo "[FAIL]  $(date '+%F %T') ${cfg#$PIPE_DIR/}"
  fi
  echo "[PROGRESS] ok=$ok fail=$fail"
  echo "----------------------------------------"
}

echo "=== phase 1/2: non-HMM configs ==="
for cfg in "${REGULAR_CFGS[@]}"; do
  run_one "$cfg"
done

echo "=== phase 2/2: inferCNV-HMM configs ==="
for cfg in "${HMM_CFGS[@]}"; do
  combo_dir=$(combo_dir_of "$cfg")
  src="${combo_dir}/infercnv"
  dst="${combo_dir}/infercnv_regular"

  # Back up the non-HMM output once, so both variants survive.
  if [[ -d "$src" && ! -e "$dst" ]]; then
    echo "[HMM] backing up $src -> $dst"
    mv "$src" "$dst"
  elif [[ -e "$dst" ]]; then
    echo "[HMM] $dst already exists — leaving as-is"
    if [[ -d "$src" ]]; then
      echo "[HMM]   removing stale $src so the HMM run starts fresh"
      rm -rf "$src"
    fi
  else
    echo "[HMM] no prior $src — running HMM fresh"
  fi

  run_one "$cfg"
done

echo "[SUMMARY] total=$((ok + fail)) ok=$ok fail=$fail"
if (( fail > 0 )); then
  echo "[FAILED_CONFIGS]"
  printf '%s\n' "${failed_cfgs[@]}"
  exit 1
fi
