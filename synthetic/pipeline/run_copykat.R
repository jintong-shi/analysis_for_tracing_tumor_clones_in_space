#!/usr/bin/env Rscript
# Run CopyKAT on Standardized_Inputs/CopyKAT (counts.rds + references.rds).
suppressPackageStartupMessages({
  library(copykat)
  library(Matrix)
  library(dplyr)
})

# ==========================================
# 1. Parse Arguments
# ==========================================
args <- commandArgs(trailingOnly=TRUE)

if (length(args) < 2) {
  stop("Usage: run_copykat.R <Input_Dir> <Output_Dir> [Threads]")
}

input_dir  <- args[1]
output_dir <- args[2]
# Optional: Allow setting threads via command line, default to 4
n_threads  <- if (length(args) >= 3) as.numeric(args[3]) else 4

# Ensure output directory exists
if (!dir.exists(output_dir)) dir.create(output_dir, recursive = TRUE)

# IMPORTANT: CopyKAT writes intermediate files to the current working directory.
# We change the working directory to output_dir to keep things organized.
setwd(output_dir)

# ==========================================
# 2. Load Data
# ==========================================
message("-> Loading inputs...")
counts_file <- file.path(input_dir, "counts.rds")
ref_file    <- file.path(input_dir, "references.rds")

if (!file.exists(counts_file)) stop(paste("Counts file missing:", counts_file))
if (!file.exists(ref_file))    stop(paste("Reference file missing:", ref_file))

# Load the raw count matrix (Genes x Cells)
raw_counts <- readRDS(counts_file)
# CopyKAT expects a dense matrix/data.frame
if (inherits(raw_counts, "dgCMatrix") || inherits(raw_counts, "sparseMatrix")) {
  raw_counts <- as.matrix(raw_counts)
}

# Load the vector of normal cell barcodes
norm_cells <- readRDS(ref_file)

# Ensure norm_cells is a character vector
if (is.list(norm_cells) || is.data.frame(norm_cells)) {
  norm_cells <- unlist(norm_cells)
}

message(sprintf("   Input Matrix: %d genes x %d spots", nrow(raw_counts), ncol(raw_counts)))
message(sprintf("   Reference Cells: %d", length(norm_cells)))

# ==========================================
# 3. Run CopyKAT
# ==========================================
message("-> Running CopyKAT...")

# Note: sam.name is the prefix for output files generated by CopyKAT
res <- copykat(
  rawmat          = raw_counts,
  norm.cell.names = norm_cells,
  n.cores         = n_threads,
  genome          = "hg20"
)

# ==========================================
# 4. Save Results
# ==========================================
message("-> Saving final RDS object...")
saveRDS(res, file.path(output_dir, "copykat_object.rds"))

message("-> Done.")
